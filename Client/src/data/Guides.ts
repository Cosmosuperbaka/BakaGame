export function findGuide(slug: string | undefined): Guide | undefined {
  return GUIDES.find((guide) => guide.slug === slug);
}

/** 页脚等紧凑位置用的短名：取主标题里的问句部分（「谁是卧底怎么玩？在线版完整规则」→「谁是卧底怎么玩」）。 */
export function guideNavLabel(guide: Guide): string {
  return guide.title.split("？")[0];
}
